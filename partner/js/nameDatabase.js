// Lowercase lookup sets for fast O(1) categorization
const boySet = new Set(BOY_NAMES.map(n => n.toLowerCase()));
const girlSet = new Set(GIRL_NAMES.map(n => n.toLowerCase()));
const neutralSet = new Set(NEUTRAL_NAMES.map(n => n.toLowerCase()));

/**
 * Extracts a candidate first name from a full student name string.
 * Handles "First Last", "Last, First", "First Middle Last", titles, etc.
 * @param {string} fullName
 * @returns {string}
 */
export function extractFirstName(fullName) {
  if (!fullName || typeof fullName !== 'string') return '';
  let cleaned = fullName.trim();
  if (!cleaned) return '';

  // Handle "Last, First"
  if (cleaned.includes(',')) {
    const parts = cleaned.split(',');
    if (parts[1] && parts[1].trim()) {
      cleaned = parts[1].trim();
    }
  }

  // Strip prefixes like Mr., Ms., Dr.
  cleaned = cleaned.replace(/^(mr\.?|mrs\.?|ms\.?|dr\.?|miss)\s+/i, '');

  // Split tokens by spaces or hyphens (keep primary first name)
  const tokens = cleaned.split(/[\s	]+/);
  if (tokens.length === 0) return '';

  let firstName = tokens[0].replace(/[^a-zA-Z\-']/g, '');
  if (firstName.includes('-')) {
    firstName = firstName.split('-')[0];
  }

  return firstName.trim();
}

/**
 * Detect gender categorization for a given student name.
 * @param {string} fullName
 * @returns {{
 *   gender: 'boy' | 'girl' | 'neutral' | 'unknown',
 *   category: 'boy' | 'girl' | 'neutral' | 'unknown',
 *   firstName: string,
 *   label: string
 * }}
 */
export function detectGender(fullName) {
  const firstName = extractFirstName(fullName);
  const lower = firstName.toLowerCase();

  if (!lower) {
    return {
      gender: 'unknown',
      category: 'unknown',
      firstName: '',
      label: 'Unknown name (needs manual sorting)'
    };
  }

  // 1. Check gender-neutral names list
  if (neutralSet.has(lower)) {
    return {
      gender: 'neutral',
      category: 'neutral',
      firstName,
      label: 'Gender-neutral name (needs manual sorting)'
    };
  }

  // 2. Check boy names
  const isBoy = boySet.has(lower);
  const isGirl = girlSet.has(lower);

  if (isBoy && !isGirl) {
    return {
      gender: 'boy',
      category: 'boy',
      firstName,
      label: 'Auto-assigned (Boy)'
    };
  }

  // 3. Check girl names
  if (isGirl && !isBoy) {
    return {
      gender: 'girl',
      category: 'girl',
      firstName,
      label: 'Auto-assigned (Girl)'
    };
  }

  // In both sets (if any overlap)
  if (isBoy && isGirl) {
    return {
      gender: 'neutral',
      category: 'neutral',
      firstName,
      label: 'Gender-neutral name (needs manual sorting)'
    };
  }

  // 4. Not in top 3,000 common names
  return {
    gender: 'unknown',
    category: 'unknown',
    firstName,
    label: 'Not in top 3,000 common names (needs manual sorting)'
  };
}
